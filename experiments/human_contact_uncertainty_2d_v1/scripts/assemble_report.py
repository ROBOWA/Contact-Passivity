"""Assemble report.md from docs/report_*.md parts (ordered by section), embed figures, append all tables."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "docs"
FIG = "outputs/figures"


def sections(text):
    """Split markdown into (heading, body) blocks at '## ' headings; text before the first is ('', ...)."""
    out, cur, buf = [], "", []
    for line in text.splitlines():
        if line.startswith("## "):
            out.append((cur, "\n".join(buf)))
            cur, buf = line, []
        else:
            buf.append(line)
    out.append((cur, "\n".join(buf)))
    return out


def main():
    head = (D / "report_head.md").read_text()
    parts = []
    for name in ["report_static_sections.md", "report_main_sections.md", "report_ablation_sections.md", "report_tail.md"]:
        parts += [s for s in sections((D / name).read_text()) if s[0]]
    order = ["## 1.", "## 2.", "## 3.", "## 4.", "## 5a.", "## 5.", "## 6.", "## 7.", "## 7b.", "## 8.", "## 9.", "## 10.",
             "## 11.", "## Completion checklist"]
    figs = {
        "## 4.": ["gp_inference_example.png", "offline_response_to_motion.png", "offline_calibration.png", "offline_residual.png"],
        "## 5a.": ["geometry.png"],
        "## 5.": ["violations_main.png", "tradeoff_main.png", "accounts_sensor_bias_100.png", "accounts_block_release_100.png",
                  "completion_main.png", "runtime_main.png"],
        "## 6.": ["moment_arm_sweep.png"],
        "## 7.": ["calibration_forks.png"],
        "## 7b.": ["refinement.png"],
    }
    used, body = set(), [head]
    for pre in order:
        for h, b in parts:
            key = h.split(" ")[0] + " " + h.split(" ")[1] if pre != "## Completion checklist" else None
            match = h.startswith(pre + " ") if pre != "## Completion checklist" else h.startswith(pre)
            if match and h not in used:
                used.add(h)
                body.append(h + "\n" + b.rstrip() + "\n")
                for f in figs.get(pre, []):
                    if (ROOT / FIG / f).exists():
                        body.append(f"![{f}]({FIG}/{f})\n")
    missing = [h for h, _ in parts if h not in used]
    for h, b in parts:
        if h in missing:
            body.append(h + "\n" + b.rstrip() + "\n")
    tables = (ROOT / "outputs" / "report_tables.md")
    if tables.exists():
        body.append("## Appendix: all result tables (generated by `scripts/build_docs.py --tables`)\n")
        body.append(re.sub(r"^## ", "### ", tables.read_text(), flags=re.M))
    (ROOT / "report.md").write_text("\n".join(body))
    print("report.md assembled;", len(used), "sections;", "unplaced:", missing)


if __name__ == "__main__":
    main()
